import { t, type TranslationDict } from "../i18n";

export interface DetailedGuardRule {
  id: string;
  name: string;
  description: string;
  category: "hygiene" | "formatting" | "linter" | "security";
  categoryLabel: string;
  phase: "fixer" | "formatter" | "linter";
  phaseLabel: string;
  fixable: boolean;
  severity: "blocker" | "warning";
  extensions: string[];
  toolName: string;
}

export function getGuardRuleName(rule: { id: string; name?: string }): string {
  const key = `guard.rule.${rule.id.replace(/[:.-]/g, "_")}.name` as keyof TranslationDict;
  return t(key) || rule.name || rule.id;
}

export function getGuardRuleDesc(rule: { id: string; description?: string }): string {
  const key = `guard.rule.${rule.id.replace(/[:.-]/g, "_")}.desc` as keyof TranslationDict;
  return t(key) || rule.description || "";
}

